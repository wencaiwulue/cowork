export function extractSmokeSummaryFromOutput(output) {
  const text = String(output ?? '').trim()
  if (!text) return undefined
  const starts = []
  for (let index = text.lastIndexOf('{'); index >= 0; index = text.lastIndexOf('{', index - 1)) {
    starts.push(index)
  }
  for (const start of starts) {
    try {
      const parsed = JSON.parse(text.slice(start))
      return parsed && typeof parsed === 'object' ? parsed : undefined
    } catch {
      // Keep scanning earlier JSON-looking fragments.
    }
  }
  return undefined
}

export function summarizeSmokeSummary(summary) {
  if (!summary || typeof summary !== 'object') return undefined
  const requiredFlags = Object.fromEntries(
    requiredSmokeSummaryFlags.map(flag => [flag, summary[flag] === true]),
  )
  return {
    ok: summary.ok === true,
    requiredFlags,
    ...(typeof summary.terminalMode === 'string' ? { terminalMode: summary.terminalMode } : {}),
  }
}

export function missingSmokeSummaryFlags(smokeSummary) {
  if (!smokeSummary || smokeSummary.ok !== true) return ['ok']
  const missing = []
  if (smokeSummary.terminalMode !== 'pty') missing.push('terminalMode=pty')
  const flags = smokeSummary.requiredFlags
  if (!flags || typeof flags !== 'object') return [...missing, ...requiredSmokeSummaryFlags]
  return [
    ...missing,
    ...requiredSmokeSummaryFlags.filter(flag => flags[flag] !== true),
  ]
}
